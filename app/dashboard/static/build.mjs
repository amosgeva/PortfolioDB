// Builds the dashboard front end. Run from the repo root: `npm run build`.
//
// Sources                         Output (committed, read by streamlit_app.py)
//   src/main.js + src/**/*.js  ->  app.js    one IIFE bundle (esbuild)
//   fonts/*.woff2              ->  fonts/fonts.css   @font-face, base64 inline
//   fonts.css + tokens.css +
//   src/styles/app.css         ->  app.css
//
// Nothing builds at runtime: the outputs are committed, so the Docker image and
// a host-run Streamlit need no Node. `--check` rebuilds in memory and fails if
// any committed output differs, which is how CI proves the committed bundle is
// the one these sources produce (frontend.yml). Line endings are normalised to
// LF before comparing, so a Windows checkout with autocrlf passes too.
//
// Fonts are inlined rather than linked because the dashboard runs in a srcdoc
// iframe and dashboard/static is not served over HTTP: a data URI is the only
// way to self-host them without a request to Google Fonts (audit A-5).

import { build } from 'esbuild';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const lf = (s) => s.replace(/\r\n/g, '\n');
const read = (p) => lf(readFileSync(join(HERE, p), 'utf8'));

const BANNER = '/* GENERATED by app/dashboard/static/build.mjs - do not edit. Edit the sources it names and run `npm run build`. */\n';

const FAMILIES = [
  { file: 'space-grotesk-latin-wght-normal.woff2', family: 'Space Grotesk', weight: '300 700',
    source: '@fontsource-variable/space-grotesk 5.3.0 (latin subset)', licence: 'OFL-SpaceGrotesk.txt' },
  { file: 'jetbrains-mono-latin-wght-normal.woff2', family: 'JetBrains Mono', weight: '100 800',
    source: '@fontsource-variable/jetbrains-mono 5.3.0 (latin subset)', licence: 'OFL-JetBrainsMono.txt' },
];
// The latin subset's range, as the upstream package declares it. Characters
// outside it (arrows such as U+2192) fall back to the next family in the stack.
const LATIN = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';

export function fontsCss() {
  const known = new Set(FAMILIES.map((f) => f.file));
  const extra = readdirSync(join(HERE, 'fonts')).filter((n) => n.endsWith('.woff2') && !known.has(n));
  if (extra.length) throw new Error('fonts/ has woff2 files build.mjs does not declare: ' + extra.join(', '));
  let out = BANNER + '/* Self-hosted fonts, SIL Open Font License 1.1 - see the OFL-*.txt files beside this one. */\n';
  for (const f of FAMILIES) {
    const b64 = readFileSync(join(HERE, 'fonts', f.file)).toString('base64');
    out += `/* ${f.family}: ${f.source}; licence fonts/${f.licence} */\n` +
      `@font-face{font-family:'${f.family}';font-style:normal;font-display:swap;font-weight:${f.weight};` +
      `src:url(data:font/woff2;base64,${b64}) format('woff2');unicode-range:${LATIN}}\n`;
  }
  return out;
}

export async function bundleJs() {
  const res = await build({
    entryPoints: [join(HERE, 'src', 'main.js')],
    bundle: true,
    format: 'iife',
    target: 'es2020',
    platform: 'browser',
    charset: 'utf8',
    legalComments: 'none',
    write: false,
    logLevel: 'warning',
  });
  return BANNER + lf(res.outputFiles[0].text);
}

export async function outputs() {
  const fonts = fontsCss();
  const css = fonts + '\n' + read('tokens.css') + '\n' + read('src/styles/app.css');
  return { 'fonts/fonts.css': fonts, 'app.css': css.endsWith('\n') ? css : css + '\n', 'app.js': await bundleJs() };
}

async function main() {
  const check = process.argv.includes('--check');
  const out = await outputs();
  const stale = [];
  for (const [rel, text] of Object.entries(out)) {
    const path = join(HERE, rel);
    let current;
    try { current = lf(readFileSync(path, 'utf8')); } catch (e) { current = null; }
    if (current === text) continue;
    if (check) stale.push(rel);
    else { writeFileSync(path, text); console.log('wrote', 'app/dashboard/static/' + rel); }
  }
  if (check && stale.length) {
    console.error('Out of date: ' + stale.map((s) => 'app/dashboard/static/' + s).join(', ') +
      '\nThe committed build does not match its sources. Run `npm run build` and commit the result.');
    process.exit(1);
  }
  if (check) console.log('build outputs match their sources');
}

if (process.argv[1] && resolve(fileURLToPath(import.meta.url)) === resolve(process.argv[1])) {
  main().catch((e) => { console.error(e); process.exit(1); });
}
