def _tag(word: str, tone: str = "neutral") -> str:
    """A status word in a tinted well (the design system's tag), never an emoji."""
    return f'<span class="m2-tag m2-tag--{tone}">{html.escape(word)}</span>'


def _local(ts: datetime | None) -> datetime | None:
    """A timestamp in the reporting timezone (the Settings value), not the
    process's — they differ whenever the zone was changed on the Settings page
    or the host runs in another zone (audit N-9)."""
    if ts is None:
        return None
    if ts.tzinfo is None:
        ts = ts.replace(tzinfo=ZoneInfo("UTC"))
    return ts.astimezone(reporting_tz.tzinfo())


def _fmt_local(ts: datetime | None) -> str:
    loc = _local(ts)
    return loc.strftime("%Y-%m-%d %H:%M") if loc else "—"


def today_local() -> date:
    """Today in the reporting timezone: the default trade date."""
    return datetime.now(reporting_tz.tzinfo()).date()


def _plain(d) -> str:
    """A Decimal as a person writes it: 20, not 2E+1; 0.5, not 0.50000000."""
    try:
        return format(Decimal(str(d)).normalize(), "f")
    except Exception:
        return str(d)


def _price(d) -> str:
    """$184.00 for a price with cents or fewer; every typed digit beyond that
    (a $0.12345 fill is real) rather than a rounding."""
    try:
        dec = Decimal(str(d))
    except Exception:
        return str(d)
    if dec == dec.quantize(Decimal("0.01")):
        return f"${dec:,.2f}"
    return "$" + _plain(dec)


def _display_frame(rows, text_cols) -> pd.DataFrame:
    """A frame for st.dataframe. Its toolbar has its own "Download as CSV",
    so free-text cells get the same formula neutralising as the export
    (audit A-4) — on screen a leading ' is a faithful, harmless rendering."""
    df = pd.DataFrame(rows)
    for col in text_cols:
        if col in df:
            df[col] = df[col].map(nw.csv_safe)
    return df


def _flash(kind: str, text: str) -> None:
    """Queue a message for the next run. Writes end in st.rerun(), which
    would wipe a message drawn before it."""
    st.session_state.setdefault("_m2_flash", []).append((kind, text))


def _show_flash() -> None:
    for kind, text in st.session_state.pop("_m2_flash", []):
        getattr(st, kind, st.info)(text)


