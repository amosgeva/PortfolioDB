@lru_cache(maxsize=1)
def design_tokens_css() -> str:
    """The front end's light ``:root`` and dark ``[data-theme="dark"]`` token
    blocks, verbatim. Raises if either is missing, so a restructured
    stylesheet fails loudly here instead of rendering an untokened page."""
    css = _TOKENS_SOURCE.read_text(encoding="utf-8")
    blocks = []
    for selector in (r":root", r'\[data-theme="dark"\]'):
        m = re.search(rf"^{selector}\{{.*?^\}}", css, re.S | re.M)
        if not m or "--accent:" not in m.group(0):
            raise RuntimeError(f"no {selector} token block in {_TOKENS_SOURCE.name}")
        blocks.append(m.group(0))
    return "\n".join(blocks)


def _mask_url(svg: str) -> str:
    # An SVG used as an image needs its namespace (dash_nav.svg(xmlns=True)).
    return 'url("data:image/svg+xml,' + quote(svg, safe="") + '")'


def _nav_css(active: str) -> str:
    """Per-entry icon masks plus the active entry's highlight, for the rail
    buttons and the tab bar buttons."""
    rules = []
    for v in dash_nav.views():
        key = v["id"]
        ico = _mask_url(dash_nav.svg(v["icon"], xmlns=True))
        rules.append(f".st-key-m2_nav_{key},.st-key-m2_tab_{key}{{--ico:{ico}}}")
    rules.append(
        f".st-key-m2_nav_{active} button{{background:oklch(34% 0.055 264)!important;"
        "color:#fff!important;box-shadow:inset 2px 0 0 var(--accent)}"
    )
    rules.append(f".st-key-m2_tab_{active} button{{color:var(--accent)!important}}")
    return "\n".join(rules)


