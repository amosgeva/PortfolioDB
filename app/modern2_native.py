def render_news_status() -> None:
    """Deliver a background news fetch to the page that asked for it.

    The fetch clears the payload cache when it lands, but an already drawn
    page does not know. While this session's run is going, a fragment polls
    every NEWS_POLL_S seconds and reruns the app when it ends, so the new
    headlines appear by themselves; then a toast says how it went.
    """
    ss = st.session_state
    mine = ss.get("_m2_news_run")
    if not mine:
        return
    job = native_jobs.status("news")
    if job.run_id != mine:
        ss.pop("_m2_news_run", None)
        return
    if job.running:
        @st.fragment(run_every=NEWS_POLL_S)
        def _poll():
            if not native_jobs.status("news").running:
                st.rerun(scope="app")

        with st.container(key="pdb_news_poll"):
            _poll()
        return
    ss.pop("_m2_news_run", None)
    if job.state == "failed":
        first = (job.error.removeprefix("RuntimeError: ").splitlines() or ["unknown error"])[0][:160]
        st.toast(f"News refresh failed: {first}")
    else:
        st.toast("Headlines updated.")


def _render_brief_job() -> None:
    """The brief runs off the page's thread (audit N-10); this shows it and
    redraws the page when it lands."""
    ss = st.session_state
    job = native_jobs.status("brief")
    if job.running:
        started = datetime.fromtimestamp(job.started_at, reporting_tz.tzinfo()).strftime("%H:%M:%S")

        @st.fragment(run_every=BRIEF_POLL_S)
        def _poll():
            if native_jobs.status("brief").running:
                st.html(f'<div class="m2-status">{_tag("running", "accent")}'
                        f"<span>Generating a brief (started {started}). The page stays usable; "
                        "it appears here when it lands.</span></div>")
            else:
                st.rerun(scope="app")

        _poll()
        return
    if job.run_id and ss.get("_m2_brief_run") == job.run_id:
        ss.pop("_m2_brief_run", None)
        if job.state == "failed":
            st.error(f"Brief failed: {job.error}")
        elif job.state == "done":
            st.success("Brief generated.")


