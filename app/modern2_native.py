def _go(view: str) -> None:
    """Rail/tab callback: change the view inside this session.

    Setting the query parameter from a callback reruns the script over the
    open websocket with the new value — no page load — and updates the
    address bar, so reload and back still land on the same view.
    """
    st.query_params["view"] = view


def _watchlist_html(watchlist) -> str:
    if not watchlist:
        return ""
    rows = []
    for w in watchlist:
        price, day = w.get("price"), w.get("dayPct")
        px = f"${float(price):,.2f}" if price is not None else "n/a"
        if day is None:
            # No prior close to compare with: say so, as the front end does,
            # rather than paint a green +0.00%.
            chg, cls = "n/a", ""
        else:
            chg, cls = f"{float(day):+.2f}%", ("up" if float(day) >= 0 else "down")
        rows.append(
            '<div class="wl__row"><span class="wl__sym">' + html.escape(str(w.get("sym", ""))) + "</span>"
            '<span class="wl__px">' + px + "</span>"
            f'<span class="wl__chg {cls}">' + chg + "</span></div>"
        )
    return '<div class="m2-rail-label">Watchlist</div><div class="m2-rail-wl">' + "".join(rows) + "</div>"


def _render_rail(active: str, watchlist=None) -> None:
    with st.container(key="m2_rail"):
        st.html(
            '<div class="m2-rail-brand"><span class="logo">' + dash_nav.svg("logo") + "</span>"
            '<span><div class="name">Portfolio<b>DB</b></div><div class="tag">Live markets</div></span></div>'
        )
        # Every group, in nav.json's order, the way the front end's rail draws them.
        for group in dash_nav.groups():
            st.html(f'<div class="m2-rail-label">{html.escape(group["label"])}</div>')
            for v in dash_nav.group_views(group["id"]):
                st.button(v["label"], key=f"m2_nav_{v['id']}", on_click=_go, args=(v["id"],), type="tertiary")
        st.html(
            _watchlist_html(watchlist)
            + '<div class="m2-rail-foot"><span class="avatar">' + html.escape(branding.display_initials()) + "</span>"
            '<span class="user"><b>' + html.escape(branding.display_name()) + "</b><span>Growth portfolio</span></span></div>"
            '<div class="m2-rail-build" title="Build ' + html.escape(app_version.build_stamp()) + '">'
            + html.escape(app_version.release_version()) + "</div>"
        )


def _render_tabbar() -> None:
    # The phone/tablet tab bar (≤980px): five entries, icon over a short label,
    # nav.json's tabbar.native. The other read-only views are one tap further,
    # through Portfolio's own menu.
    with st.container(key="m2_tabbar"):
        for v in dash_nav.tabbar("native"):
            st.button(v["short"], key=f"m2_tab_{v['id']}", on_click=_go, args=(v["id"],), type="tertiary")


def inject_shell(active: str, watchlist=None) -> None:
    """Rail, tab bar, theme and the page heading. The heading is the view's
    nav.json label and subtitle, as the front end's own panes use theirs."""
    meta = dash_nav.view(active)
    title, subtitle = meta["label"], meta["subtitle"]
    st.markdown(f"<style>{page_css(active)}</style>", unsafe_allow_html=True)
    # Apply the dashboard's saved light/dark theme to this native page. Scripts
    # in st.markdown are stripped, so a tiny same-origin iframe sets data-theme
    # on the parent document instead. st.iframe (the components.html successor)
    # rejects height=0, so the keyed container parks it off-screen via CSS.
    with st.container(key="m2_theme_shim"):
        st.iframe(
            """<script>
            try {
              var t = localStorage.getItem('pdb_theme') ||
                (window.matchMedia && matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light');
              window.parent.document.documentElement.setAttribute('data-theme', t);
            } catch (e) {}
            </script>""",
            height=1,
        )
    _render_rail(active, watchlist)
    _render_tabbar()
    st.markdown(
        f'<div class="m2-topbar"><h1>{html.escape(title)}</h1><p>{html.escape(subtitle)}</p></div>',
        unsafe_allow_html=True,
    )


# ── the write gate ─────────────────────────────────────────────────────────


def _client_id() -> str:
    """Who the throttle counts failures against: the peer address, when the
    server knows one as text."""
    try:
        ip = st.context.ip_address
    except Exception:
        return "unknown"
    return ip if isinstance(ip, str) and ip else "unknown"


def _try_unlock() -> None:
    """Unlock form callback. The typed value is read once, checked, and wiped
    from session state before the next run draws the page."""
    ss = st.session_state
    candidate = ss.get("m2_unlock_pw") or ""
    ss["m2_unlock_pw"] = ""
    result = native_auth.attempt(candidate, ss, client=_client_id())
    _flash("success" if result.ok else "error", result.message)


def _lock() -> None:
    native_auth.lock(st.session_state)
    _flash("info", "Writes locked for this browser session.")


def render_gate() -> bool:
    """The write-access strip at the top of a write page. Returns whether
    this session may write. Read-only content renders either way."""
    var = native_auth.PASSWORD_ENV
    if not native_auth.configured():
        st.html(
            f'<div class="m2-gate">{_tag("read-only", "warn")}'
            f"<span>Changes are disabled until a dashboard password is set: run "
            "<code>make init</code> (or <code>pdb.ps1 init</code>), which adds "
            f"<code>{var}</code> to the repo-root <code>.env</code>, or add a long random value "
            "by hand; then restart the dashboard.</span></div>"
        )
        return False
    if native_auth.is_unlocked(st.session_state):
        g1, g2 = st.columns([5, 1], vertical_alignment="center")
        g1.html(
            f'<div class="m2-gate">{_tag("unlocked", "ok")}'
            "<span>Changes are enabled for this browser session.</span></div>"
        )
        g2.button("Lock", key="m2_lock", on_click=_lock, width="stretch")
        return True
    with st.form("m2_unlock", clear_on_submit=True, border=False):
        st.html(
            f'<div class="m2-gate">{_tag("locked", "neutral")}'
            "<span>Viewing is open. Recording, deleting, saving and model calls need the "
            "dashboard password.</span></div>"
        )
        u1, u2 = st.columns([4, 1], vertical_alignment="bottom")
        u1.text_input(
            "Dashboard password", type="password", key="m2_unlock_pw",
            autocomplete="current-password",
        )
        u2.form_submit_button("Unlock", type="primary", on_click=_try_unlock, width="stretch", key="m2_unlock_submit")
    return False


def _may_write() -> bool:
    """The server-side check, made at the moment of writing. A disabled
    button is a courtesy; this is the control."""
    try:
        native_auth.require_unlocked(st.session_state)
    except native_auth.WriteLocked as exc:
        st.error(str(exc))
        return False
    return True


def _done(kind: str, text: str) -> None:
    """After a committed write: queue the message, drop cached reads, rerun."""
    _flash(kind, text)
    st.cache_data.clear()
    st.rerun()


# ── drafts ────────────────────────────────────────────────────────────────
# Every field an operator types into on these pages is a draft that must
# survive navigation (audit N-5). Three Streamlit facts make that work:
#   * no st.form around them: a form holds what was typed in the browser until
#     submit, so a rail click could never carry it to the server;
#   * on_change="ignore": a value is not a rerun of its own, but rides along
#     with the next one — the Add button, or the rail click that leaves;
#   * persist_state="session": the value is kept while the widget is not
#     drawn (another view, or the iframe), and comes back with the page.
# The password, the delete reason and the delete-by-ID number stay ephemeral
# on purpose.
DRAFT = {"on_change": "ignore", "persist_state": "session"}


