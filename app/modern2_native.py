"""Native (server-interactive) pages for the modern v2 dashboard.

The immersive design lives in a sandboxed ``components.html`` iframe, which is
great for read-only surfaces but cannot write to the DB or call a model. The
**Manage** (DB writes and Settings), **Advisor** (model briefs + chat) and
**Data Health** surfaces are therefore rendered with native Streamlit widgets,
themed with the same design tokens (read from the front end's own stylesheet,
see :func:`design_tokens_css`) so they feel like the same product.

Three rules hold across every page here:

* **Writes are gated.** Every write and every paid model call needs the
  dashboard password (``native_auth``): the forms render disabled until the
  session is unlocked, and each handler calls ``native_auth.require_unlocked``
  again immediately before it writes. The SQL itself is in ``native_writes``.
* **Navigation stays in the session.** The rail and the phone tab bar are
  Streamlit buttons whose callbacks set ``st.query_params["view"]``, so moving
  between views is a rerun over the open websocket, not a page load: form
  state, the unlock and the warm caches survive (audit N-5). The URL still
  changes, so a reload or a bookmark lands on the same view.
* **Times are the reporting timezone's**, not the process's (audit N-9).
"""

